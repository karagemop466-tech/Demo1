#!/usr/bin/env python3
"""Render audit/register.json into audit/REPORT.md and audit/index.html.

Stdlib only. Run from anywhere:  python3 audit/build_audit.py
Every check row must carry an https source link; the script exits non-zero otherwise.
"""
import html
import json
import pathlib
import sys
from collections import Counter

HERE = pathlib.Path(__file__).resolve().parent
reg = json.loads((HERE / "register.json").read_text(encoding="utf-8"))

problems = []
for c in reg["checks"]:
    if not str(c.get("source", "")).startswith("https://"):
        problems.append(f"{c['id']}: source is not an https link")
    if c.get("result") not in reg["meta"]["result_legend"]:
        problems.append(f"{c['id']}: unknown result {c.get('result')!r}")
for s in reg["sources"]:
    if not s["url"].startswith("https://"):
        problems.append(f"{s['id']}: source url is not https")
if problems:
    print("\n".join(problems))
    sys.exit(1)

counts = Counter(c["result"] for c in reg["checks"])
ORDER = ["Mismatch", "Irregularity", "Unverified", "Confirmed"]


def md_cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def md_link(url):
    return f"[{url.replace('https://', '')}]({url})"


lines = []
lines.append("# Task 23 — Code-to-official-spec audit")
lines.append("")
lines.append(f"- Audited: {reg['meta']['audited_on']}  ·  base: `{reg['meta']['base_commit']}`")
lines.append(f"- Scope: {reg['meta']['scope']}")
lines.append(f"- Method: {reg['meta']['method']}")
lines.append("")
lines.append("## Summary")
lines.append("")
lines.append("| Result | Count | Meaning |")
lines.append("|---|---|---|")
for k in ORDER:
    lines.append(f"| {k} | {counts.get(k, 0)} | {md_cell(reg['meta']['result_legend'][k])} |")
lines.append("")
lines.append("## Checks")
lines.append("")
lines.append("| ID | Area | Check | Code (file:line) | Official source | Result | Note | Action |")
lines.append("|---|---|---|---|---|---|---|---|")
for c in reg["checks"]:
    lines.append("| " + " | ".join([
        md_cell(c["id"]), md_cell(c["area"]), md_cell(c["check"]), md_cell(c["code"]),
        md_link(c["source"]), md_cell(c["result"]), md_cell(c["note"]), md_cell(c["action"]),
    ]) + " |")
lines.append("")
lines.append("## Change requests (owned files — logged, not applied)")
lines.append("")
lines.append("| ID | Owner | File | Request |")
lines.append("|---|---|---|---|")
for r in reg["change_requests"]:
    lines.append(f"| {md_cell(r['id'])} | {md_cell(r['owner'])} | {md_cell(r['file'])} | {md_cell(r['request'])} |")
lines.append("")
lines.append("## Sources used")
lines.append("")
lines.append("| ID | Source | Access | Used for |")
lines.append("|---|---|---|---|")
for s in reg["sources"]:
    lines.append(f"| {s['id']} | {md_link(s['url'])} | {md_cell(s['access'])} | {md_cell(s['used_for'])} |")
lines.append("")
lines.append("Generated by `audit/build_audit.py` from `audit/register.json`. Do not edit this file by hand.")
(HERE / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def e(x):
    return html.escape(str(x), quote=True)


COLOR = {"Confirmed": "#0a7d3b", "Mismatch": "#b00020", "Irregularity": "#b26a00", "Unverified": "#555"}
rows = []
for c in reg["checks"]:
    col = COLOR.get(c["result"], "#000")
    rows.append(
        "<tr>"
        f"<td>{e(c['id'])}</td><td>{e(c['area'])}</td><td>{e(c['check'])}</td>"
        f"<td class='mono'>{e(c['code'])}</td>"
        f"<td><a href='{e(c['source'])}' target='_blank' rel='noopener'>official ↗</a></td>"
        f"<td><b style='color:{col}'>{e(c['result'])}</b></td>"
        f"<td>{e(c['note'])}</td><td>{e(c['action'])}</td>"
        "</tr>"
    )
cr_rows = "".join(
    f"<tr><td>{e(r['id'])}</td><td>{e(r['owner'])}</td><td class='mono'>{e(r['file'])}</td><td>{e(r['request'])}</td></tr>"
    for r in reg["change_requests"]
)
src_rows = "".join(
    f"<tr><td>{e(s['id'])}</td><td><a href='{e(s['url'])}' target='_blank' rel='noopener'>{e(s['url'])}</a></td>"
    f"<td>{e(s['access'])}</td><td>{e(s['used_for'])}</td></tr>"
    for s in reg["sources"]
)
summary = " · ".join(f"<b style='color:{COLOR[k]}'>{k}: {counts.get(k, 0)}</b>" for k in ORDER)

page = f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Audit — code vs official Kalshi API (task 23)</title>
<style>
 body{{font:14px/1.45 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;margin:0;background:#f6f7f9;color:#111}}
 header{{background:#0f172a;color:#fff;padding:18px 24px}}
 header a{{color:#9be7c4}}
 main{{padding:18px 24px;max-width:1400px;margin:0 auto}}
 h1{{font-size:20px;margin:0 0 6px}} h2{{font-size:16px;margin:26px 0 8px}}
 .box{{background:#fff;border:1px solid #dde1e7;border-radius:8px;padding:12px 14px;margin-bottom:12px}}
 table{{width:100%;border-collapse:collapse;background:#fff;border:1px solid #dde1e7}}
 th,td{{padding:7px 8px;border-bottom:1px solid #eceff3;vertical-align:top;text-align:left}}
 th{{background:#eef2f6;position:sticky;top:0}}
 .mono{{font-family:ui-monospace,Menlo,Consolas,monospace;font-size:12px;word-break:break-word}}
 .scroll{{overflow-x:auto}}
</style></head>
<body>
<header>
 <h1>Audit: code vs official Kalshi API</h1>
 <div>Task 23 · session arena/639ec37c-demo1 · audited {e(reg['meta']['audited_on'])} · base {e(reg['meta']['base_commit'])}</div>
 <div style="margin-top:6px">Result counts: {summary}</div>
</header>
<main>
<div class="box">
 <b>What this is.</b> {e(reg['meta']['scope'])}<br>
 <b>How it was checked.</b> {e(reg['meta']['method'])}<br>
 <b>Not done here.</b> No orders were placed and no credentials were used. Values that could not be confirmed are marked <i>Unverified</i>, not assumed.
 Read-only: the page does not call Kalshi from the browser.
</div>

<h2>Checks</h2>
<div class="scroll"><table>
<thead><tr><th>ID</th><th>Area</th><th>Check</th><th>Code (file:line)</th><th>Official source</th><th>Result</th><th>Note</th><th>Action</th></tr></thead>
<tbody>{''.join(rows)}</tbody>
</table></div>

<h2>Change requests (logged for the owning session; not applied here)</h2>
<div class="scroll"><table>
<thead><tr><th>ID</th><th>Owner</th><th>File</th><th>Request</th></tr></thead>
<tbody>{cr_rows}</tbody>
</table></div>

<h2>Sources used</h2>
<div class="scroll"><table>
<thead><tr><th>ID</th><th>Source</th><th>Access</th><th>Used for</th></tr></thead>
<tbody>{src_rows}</tbody>
</table></div>
<p class="box">Data file: <a href="register.json">register.json</a> · Report: <a href="REPORT.md">REPORT.md</a></p>
</main></body></html>
"""
(HERE / "index.html").write_text(page, encoding="utf-8")
print(f"wrote REPORT.md and index.html: {len(reg['checks'])} checks, {len(reg['sources'])} sources, counts={dict(counts)}")
